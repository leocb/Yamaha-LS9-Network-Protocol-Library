#!/usr/bin/env python3
"""Generate Ls9Parameters.java from ls9-parameters.csv."""
import csv
import os
import re
from collections import OrderedDict

ROOT = os.path.normpath(os.path.join(os.path.dirname(__file__), ".."))
CSV = os.path.join(ROOT, "src", "main", "resources", "io", "github", "leocb", "ls9", "ls9-parameters.csv")
OUT = os.path.join(ROOT, "src", "main", "java", "io", "github", "leocb", "ls9", "sysex", "Ls9Parameters.java")


def jstr(s):
    return '"' + str(s).replace("\\", "\\\\").replace('"', '\\"') + '"'


def ident(s):
    s = re.sub(r"[^A-Za-z0-9_]", "_", s or "p")
    if not s or s[0].isdigit():
        s = "_" + s
    return s


def main():
    groups = OrderedDict()
    with open(CSV, newline="") as f:
        for row in csv.DictReader(f):
            el = row["element"] or "misc"
            groups.setdefault(el, []).append(row)

    lines = []
    lines.append("package io.github.leocb.ls9.sysex;")
    lines.append("")
    lines.append("/**")
    lines.append(" * Every parameter entry from Yamaha's ParamChangeList_LS9.xls.")
    lines.append(" * Generated by tools/generate_java_parameters.py; do not edit.")
    lines.append(" */")
    lines.append("public final class Ls9Parameters {")
    lines.append("    private Ls9Parameters() {")
    lines.append("    }")
    for el, rows in groups.items():
        cls = ident(el)
        lines.append("")
        lines.append("    public static final class " + cls + " {")
        lines.append("        private " + cls + "() {")
        lines.append("        }")
        used = set()
        for row in rows:
            field = ident(row["index_name"] or "p")
            base = field
            n = 2
            while field in used:
                field = base + "_" + str(n)
                n += 1
            used.add(field)
            comment = row["comment"]
            lines.append("        public static final ParameterSpec " + field + " = new ParameterSpec(")
            lines.append("                " + jstr(row["element"]) + ", " + jstr(row["index_name"]) + ",")
            lines.append("                " + row["element_hex"] + ", " + row["index_hex"] + ",")
            lines.append("                " + jstr(row["min"]) + ", " + jstr(row["max"]) + ", "
                         + jstr(row["default"]) + ",")
            lines.append("                " + str(int(float(row["max_ch"] or 0))) + ", "
                         + jstr(comment) + ", " + str(int(float(row["value_table"] or 0))) + ");")
        lines.append("    }")
    lines.append("}")
    with open(OUT, "w") as f:
        f.write("\n".join(lines) + "\n")
    print("wrote %s (%d elements, %d rows)" % (OUT, len(groups), sum(len(v) for v in groups.values())))


if __name__ == "__main__":
    main()
